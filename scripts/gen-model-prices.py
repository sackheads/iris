#!/usr/bin/env python3
"""Regenerates Sources/IrisKit/ModelPriceSnapshot.swift from LiteLLM's price table (#884).

    python3 -I scripts/gen-model-prices.py                 # fetch the pinned commit, rewrite the Swift file
    python3 -I scripts/gen-model-prices.py --check         # fetch it, compare, change nothing; exit 1 on a difference
    python3 -I scripts/gen-model-prices.py --input FILE    # use a local copy of the JSON instead of fetching
    python3 -I scripts/gen-model-prices.py --commit SHA --as-of YYYY-MM-DD   # move the pin

Standard library only. The snapshot is pinned to a LiteLLM commit, not to `main`, so a rerun gives the
same bytes. To refresh it, move the pin (a full 40-character SHA and the date it was current) and
commit the result. `ModelPriceSnapshot.source` stays the `main` URL on purpose: that is the live feed
`ModelPriceFeed` refreshes from at run time, while the rows are this commit's.

Rows: every entry whose `litellm_provider` is anthropic, deepseek, gemini or openai and whose `mode` is
`chat` or `responses`, with a non-zero input and output price, keyed `family|model` (the model without
the provider's `family/` prefix), sorted. The four prices are USD per token as Python's `repr` writes
them: input, output, cache read, cache creation; an absent one is an empty field.

The pinned commit is the last one LiteLLM merged on 2026-10-19 (UTC), `b2f0f4d54c5d`. The rows of the
snapshot that was committed before this script existed are reproduced exactly by that commit and by the
other commits of that day I tried (d07e3c5cd273, 748c973f421f, 0197b961716f) and by the first of the
next (ece162740855): those days' price changes did not touch these rows, so the old snapshot does not
say which commit it came from, and this pin is a choice, not a recovery.
"""
import argparse
import json
import pathlib
import sys
import urllib.request

PINNED_COMMIT = "b2f0f4d54c5dace1c1f6ad7b3c2f3bc68cb5982b"
AS_OF = "2026-10-19"

FAMILIES = ("anthropic", "deepseek", "gemini", "openai")
MODES = ("chat", "responses")
FILE = "model_prices_and_context_window.json"
RAW = "https://raw.githubusercontent.com/BerriAI/litellm"
LIVE_SOURCE = f"{RAW}/main/{FILE}"
OUT = pathlib.Path(__file__).resolve().parents[1] / "Sources" / "IrisKit" / "ModelPriceSnapshot.swift"


def fmt(x):
    return "" if x is None else repr(float(x))


def rows(table):
    out = {}
    for key, v in table.items():
        if not isinstance(v, dict):
            continue
        family = v.get("litellm_provider")
        if family not in FAMILIES or v.get("mode") not in MODES:
            continue
        inp, outp = v.get("input_cost_per_token"), v.get("output_cost_per_token")
        if not inp or not outp:
            continue
        model = key.split("/", 1)[1] if key.startswith(family + "/") else key
        out[(family, model)] = "|".join([family, model, fmt(inp), fmt(outp),
                                         fmt(v.get("cache_read_input_token_cost")),
                                         fmt(v.get("cache_creation_input_token_cost"))])
    return [out[k] for k in sorted(out)]


def render(table, commit, as_of):
    body = "\n".join("        " + r for r in rows(table))
    return (f"// Generated by scripts/gen-model-prices.py from {RAW}/{commit}/{FILE} on {as_of}. "
            "Do not edit; rerun the script.\n"
            "// family|model|input|output|cacheRead|cacheWrite, USD per token; an empty field is unknown.\n"
            "\n"
            "enum ModelPriceSnapshot {\n"
            f'    static let asOf = "{as_of}"\n'
            f'    static let source = "{LIVE_SOURCE}"\n'
            '    static let rows: String = """\n'
            f"{body}\n"
            '        """\n'
            "}\n")


def main():
    p = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    p.add_argument("--commit", default=PINNED_COMMIT, help="a full 40-character LiteLLM commit SHA")
    p.add_argument("--as-of", default=AS_OF, help="the date that commit was current, YYYY-MM-DD")
    p.add_argument("--input", help="a local copy of the JSON at that commit, instead of fetching it")
    p.add_argument("--check", action="store_true", help="compare with the committed file and change nothing")
    a = p.parse_args()
    if (a.commit == PINNED_COMMIT) != (a.as_of == AS_OF):
        sys.exit("move the pin with both --commit and --as-of")
    if len(a.commit) != 40 or any(c not in "0123456789abcdef" for c in a.commit):
        sys.exit("--commit takes a full 40-character lowercase SHA, so the pin cannot drift")
    if a.input:
        text = pathlib.Path(a.input).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(f"{RAW}/{a.commit}/{FILE}", timeout=120) as r:
            text = r.read().decode("utf-8")
    result = render(json.loads(text), a.commit, a.as_of)
    if a.check:
        same = OUT.read_text(encoding="utf-8") == result
        print("ModelPriceSnapshot.swift matches" if same else "ModelPriceSnapshot.swift differs from a fresh render")
        sys.exit(0 if same else 1)
    OUT.write_text(result, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows(json.loads(text)))} rows, {a.commit[:12]}, {a.as_of})")


if __name__ == "__main__":
    main()
